/* ============ Уникальные варианты для повторяемых «болталок» ============
   Каждая сцена из списков replay при повторе показывает ещё не виденный
   вариант реплик (alt) вместо дословного повтора. Когда варианты кончились,
   сцена больше не запускается вовсе (см. engine: _activateNode / readyPool).
   Продолжения выбора — новые сцены с суффиксом r1. */
'use strict';

function ALT(nodeId, alt){
  const sc = GD.scenes[nodeId];
  if (!sc){ console.warn('[alt] нет сцены: ' + nodeId); return; }
  if (!sc.alts) sc.alts = [];
  sc.alts.push(alt);
}

