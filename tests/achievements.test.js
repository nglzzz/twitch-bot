test('scheduled checks grant a follow anniversary without another message or website visit', () => {
  const now = Date.now();
  communityRepo.recordChat({ userId: 'anniversary-user', username: 'anniversary_user', message: 'Привет', messageId: 'anniversary-message', createdAt: now });
  communityRepo.setFollowState({ userId: 'anniversary-user', isFollowing: true,
    followedAt: now - 7 * DAY_MS + 60_000, checkedAt: now });
  assert.equal(achievementService.getEarned('anniversary-user').some((entry) => entry.achievementId === 'follow_days_7'), false);

  achievementService.evaluateFollowMilestones({ now: now + 60_001 });
  const earned = achievementService.getEarned('anniversary-user');
  assert.equal(earned.filter((entry) => entry.achievementId === 'follow_days_7').length, 1);
  assert.equal(earned.find((entry) => entry.achievementId === 'follow_days_7').announcedAt, null);
  achievementService.evaluateFollowMilestones({ now: now + 60_002 });
  assert.equal(achievementService.getEarned('anniversary-user').filter((entry) => entry.achievementId === 'follow_days_7').length, 1);
});

test('schema v4 adds identity, follow, and achievement tables to an existing database', () => {
  const { STATEMENTS, upgradeSchema } = require('../src/app/schema');
  const legacyDb = new Database(':memory:');
  try {
    for (const statement of STATEMENTS) {
      if (/community_achievement/.test(statement)) continue;
      const oldStatement = statement
        .replace('    current_followed_at INTEGER,\n', '')
        .replace('    identity_checked_at INTEGER,\n', '')
        .replace('    follow_status INTEGER,\n', '')
        .replace('    follow_checked_at INTEGER,\n', '')
        .replace('    avatar_url TEXT,\n', '')
        .replace('    avatar_checked_at INTEGER,\n', '');
      legacyDb.exec(oldStatement);
    }
    legacyDb.prepare(`INSERT INTO community_user
      (user_id, username, display_name, first_seen_at, last_seen_at, created_at, updated_at)
      VALUES ('legacy-v3', 'legacy_v3', 'Legacy', 100, 100, 100, 100)`).run();

    upgradeSchema(legacyDb);
    upgradeSchema(legacyDb);
    const columns = new Set(legacyDb.prepare('PRAGMA table_info(community_user)').all().map(({ name }) => name));
    for (const column of ['identity_checked_at', 'avatar_url', 'current_followed_at', 'follow_status', 'follow_checked_at']) {
      assert.equal(columns.has(column), true, `${column} should be added`);
    }
    assert.deepEqual(legacyDb.prepare('SELECT user_id, username FROM community_user').get(), { user_id: 'legacy-v3', username: 'legacy_v3' });
    assert.equal(legacyDb.prepare('SELECT COUNT(*) AS count FROM community_achievement').get().count, 0);
    assert.equal(legacyDb.prepare('SELECT COUNT(*) AS count FROM community_achievement_state').get().count, 0);
  } finally {
    legacyDb.close();
  }
});
