test('achievement cards retain persisted earned state after a current follow ends', () => {
  const now = Date.now();
  addUser('follow-user', 'follow_user', now);
  db.prepare('UPDATE community_user SET followed_at = ?, current_followed_at = ?, follow_status = 1, follow_checked_at = ? WHERE user_id = ?')
    .run(now - 40 * DAY_MS, null, 0, 'follow-user');
  achievementService.seedBaseline('follow-user', { now });
  db.prepare('UPDATE community_user SET current_followed_at = ?, follow_status = 1, follow_checked_at = ? WHERE user_id = ?')
    .run(now - 40 * DAY_MS, now, 'follow-user');
  const awarded = achievementService.evaluateUser('follow-user', { now });
  assert.ok(awarded.some((entry) => entry.id === 'follow_days_30'));

  db.prepare('UPDATE community_user SET follow_status = 0, follow_checked_at = ? WHERE user_id = ?')
    .run(now + DAY_MS, 'follow-user');
  const earned = new Set(achievementService.getEarned('follow-user').map((entry) => entry.achievementId));
  assert.equal(earned.has('follow_days_30'), true);
  const catalog = makeAchievements({ followedAt: now - 40 * DAY_MS, followStatus: 0, followCheckedAt: now + DAY_MS }, {}, now + DAY_MS);
  assert.equal(catalog.find((entry) => entry.id === 'follow_days_30').unlocked, false);
});

