function addUser(userId, username, now = Date.now()) {
  db.prepare(`INSERT INTO community_user
    (user_id, username, display_name, first_seen_at, last_seen_at, created_at, updated_at)
    VALUES (?, ?, ?, ?, ?, ?, ?)`)
    .run(userId, username, username, now, now, now, now);
}

function addLegacyMessage(username, index, now) {
  db.prepare(`INSERT INTO chat_log (id, user, display_name, message, created_at, updated_at)
    VALUES (?, ?, ?, ?, ?, ?)`)
    .run(`legacy-${username}-${index}`, username, username, 'Message', now + index, now + index);
}

test('first profile observation seeds earned history silently before new activity', () => {
  const now = Date.now();
  addUser('baseline-user', 'baseline_user', now);
  db.prepare('INSERT INTO quiz_score (user_id, username, display_name, points, updated_at) VALUES (?, ?, ?, ?, ?)')
    .run('baseline-user', 'baseline_user', 'baseline_user', 100, now);
  for (let index = 0; index < 100; index += 1) addLegacyMessage('baseline_user', index, now - 1000);

  assert.equal(achievementService.seedBaseline('baseline-user', { now }), true);
  assert.equal(achievementService.seedBaseline('baseline-user', { now: now + 1 }), false);
  const earned = new Set(achievementService.getEarned('baseline-user').map((entry) => entry.achievementId));
  assert.equal(earned.has('messages_100'), true);
  assert.equal(earned.has('quiz_100'), true);
  assert.equal(achievementRepo.getPendingAnnouncements().length, 0);
  const events = achievementService.getRecentAchievements({ userId: 'baseline-user' });
  assert.ok(events.every((entry) => entry.isHistorical));
  assert.ok(events.every((entry) => entry.earnedAt === now));
});

test('new unlocks are persistent, announced once, and never regenerated by profile reads', () => {
  const now = Date.now();
  addUser('new-user', 'new_user', now);
  assert.equal(achievementService.seedBaseline('new-user', { now }), true);

  for (let index = 0; index < 100; index += 1) addLegacyMessage('new_user', index, now + index + 1);
  const unlocks = achievementService.evaluateUser('new-user', { now: now + 500 });
  assert.deepEqual(new Set(unlocks.map((entry) => entry.id)), new Set(['messages_1', 'messages_100']));
  assert.equal(achievementService.evaluateUser('new-user', { now: now + 501 }).length, 0);
  assert.equal(achievementRepo.getPendingAnnouncements().length, 1);
  assert.equal(achievementService.getRecentAchievements({ userId: 'new-user' }).length, 2);

  const durableIds = achievementService.getEarned('new-user').map((entry) => entry.achievementId);
  assert.deepEqual(new Set(durableIds), new Set(['messages_1', 'messages_100']));
  achievementRepo.markAnnounced({ userId: 'new-user', achievementIds: durableIds, announcedAt: now + 600 });
});

test('real message and quiz repository hooks persist milestones exactly when counters cross targets', () => {
  const user = { userId: 'hook-user', username: 'hook_user', displayName: 'Hook User' };
  communityRepo.recordChat({ ...user, message: 'Первое сообщение', messageId: 'hook-first-message' });
  const firstMessage = new Set(achievementService.getEarned(user.userId).map((entry) => entry.achievementId));
  assert.equal(firstMessage.has('messages_1'), true);

  for (let index = 0; index < 100; index += 1) {
    quizRepo.addPoint({ ...user, mode: 'quiz', createdAt: Date.now() + index });
  }
  const earned = new Set(achievementService.getEarned(user.userId).map((entry) => entry.achievementId));
  assert.equal(earned.has('quiz_1'), true);
  assert.equal(earned.has('quiz_100'), true);
  assert.equal(earned.has('mode_quiz_25'), true);
  const pending = achievementRepo.getPendingAnnouncements().find((entry) => entry.userId === user.userId);
  assert.deepEqual(new Set(pending.achievements.map((entry) => entry.id)), new Set(['messages_1', 'quiz_1', 'mode_quiz_25', 'quiz_100']));
  achievementRepo.markAnnounced({ userId: user.userId, achievementIds: pending.achievements.map((entry) => entry.id) });
});

test('follow-duration milestones require a fresh positive Twitch verification', () => {
  const now = Date.now();
  const lifetimeFollow = {
    followedAt: now - 500 * DAY_MS,
    currentFollowedAt: now - 400 * DAY_MS,
    followStatus: 1,
    followCheckedAt: now,
  };
  const atYear = makeAchievements(lifetimeFollow, {}, now).filter((entry) => entry.id.startsWith('follow_days_'));
  assert.deepEqual(atYear.filter((entry) => entry.unlocked).map((entry) => entry.target), [7, 30, 90, 180, 365]);

  const oneDayStale = makeAchievements({ ...lifetimeFollow, followCheckedAt: now - DAY_MS - 1 }, {}, now);
  assert.equal(oneDayStale.find((entry) => entry.id === 'follow_days_365').unlocked, false);
  assert.equal(oneDayStale.find((entry) => entry.id === 'follow').unlocked, true);

  const noLongerFollowing = makeAchievements({ ...lifetimeFollow, followStatus: 0 }, {}, now);
  assert.equal(noLongerFollowing.find((entry) => entry.id === 'follow_days_7').unlocked, false);
  assert.equal(noLongerFollowing.find((entry) => entry.id === 'follow').unlocked, true);

  const dayBefore = makeAchievements({ ...lifetimeFollow, currentFollowedAt: now - 364 * DAY_MS - 1 }, {}, now);
  assert.equal(dayBefore.find((entry) => entry.id === 'follow_days_365').unlocked, false);
  const atDay365 = makeAchievements({ ...lifetimeFollow, currentFollowedAt: now - 365 * DAY_MS }, {}, now);
  assert.equal(atDay365.find((entry) => entry.id === 'follow_days_365').unlocked, true);
});

test('Twitch chat announcement groups achievements and retries without acknowledging a failure', async () => {
  const now = Date.now();
  addUser('announce-user', 'stream_friend', now);
  assert.equal(achievementRepo.seedBaseline({ userId: 'announce-user', earnedIds: [], initializedAt: now }), true);
  for (const achievementId of ['messages_1', 'messages_100', 'messages_1000', 'messages_5000']) {
    assert.equal(achievementRepo.insertEarned({ userId: 'announce-user', achievementId, earnedAt: now, announce: true }), true);
  }

  const messages = [];
  let failFirst = true;
  const worker = achievementService.createAnnouncementWorker({
    chat: { getClient: () => ({ readyState: () => 'OPEN', say: async (_channel, message) => {
      if (failFirst) { failFirst = false; throw new Error('temporary chat outage'); }
      messages.push(message);
      return 'sent';
    } }) },
    isDbReady: () => true,
    channel: 'test_channel',
    now: () => now + 1,
    logger: { warn() {}, error() {} },
  });

  assert.equal(await worker.poll(), 0);
  assert.equal(achievementRepo.getPendingAnnouncements().length, 1);
  assert.equal(await worker.poll(), 1);
  assert.equal(messages.length, 1);
  assert.match(messages[0], /@stream_friend/);
  assert.match(messages[0], /и ещё 1/);
  assert.equal(achievementRepo.getPendingAnnouncements().length, 0);
  worker.stop();
});

test('recent achievements and pending notices use only the current owner of a reused login', () => {
  const now = Date.now();
  addUser('previous-owner', 'reused_login', now - 100);
  addUser('current-owner', 'reused_login', now);
  db.prepare('UPDATE community_user SET identity_checked_at = ? WHERE user_id = ?').run(now - 100, 'previous-owner');
  db.prepare('UPDATE community_user SET identity_checked_at = ? WHERE user_id = ?').run(now, 'current-owner');
  achievementRepo.seedBaseline({ userId: 'previous-owner', earnedIds: [], initializedAt: now - 100 });
  achievementRepo.seedBaseline({ userId: 'current-owner', earnedIds: [], initializedAt: now });
  achievementRepo.insertEarned({ userId: 'previous-owner', achievementId: 'messages_1', earnedAt: now - 100, announce: true });
  achievementRepo.insertEarned({ userId: 'current-owner', achievementId: 'quiz_1', earnedAt: now, announce: true });

  assert.equal(achievementService.getRecentAchievements({ limit: 20 }).some((entry) => entry.login === 'reused_login' && entry.achievementId === 'messages_1'), false);
  assert.equal(achievementService.getRecentAchievements({ limit: 20 }).some((entry) => Object.hasOwn(entry, 'userId')), false);
  assert.deepEqual(achievementRepo.getPendingAnnouncements().map((entry) => entry.userId), ['current-owner']);
});

test('achievement cards retain persisted earned state after a current follow ends', () => {
  const now = Date.now();
  addUser('follow-user', 'follow_user', now);
  db.prepare('UPDATE community_user SET followed_at = ?, current_followed_at = ?, follow_status = 1, follow_checked_at = ? WHERE user_id = ?')
    .run(now - 40 * DAY_MS, null, 0, 'follow-user');
  achievementService.seedBaseline('follow-user', { now });
  db.prepare('UPDATE community_user SET current_followed_at = ?, follow_status = 1, follow_checked_at = ? WHERE user_id = ?')
    .run(now - 40 * DAY_MS, now, 'follow-user');
  const awarded = achievementService.evaluateUser('follow-user', { now });
  assert.ok(awarded.some((entry) => entry.id === 'follow_days_30'));

  db.prepare('UPDATE community_user SET follow_status = 0, follow_checked_at = ? WHERE user_id = ?')
    .run(now + DAY_MS, 'follow-user');
  const earned = new Set(achievementService.getEarned('follow-user').map((entry) => entry.achievementId));
  assert.equal(earned.has('follow_days_30'), true);
  const catalog = makeAchievements({ followedAt: now - 40 * DAY_MS, followStatus: 0, followCheckedAt: now + DAY_MS }, {}, now + DAY_MS);
  assert.equal(catalog.find((entry) => entry.id === 'follow_days_30').unlocked, false);
});

