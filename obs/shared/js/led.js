  // Латиница, совпадающая по начертанию с кириллицей.
  const SAME = { A: 'А', B: 'В', C: 'С', E: 'Е', H: 'Н', K: 'К', M: 'М', O: 'О', P: 'Р', T: 'Т', X: 'Х' };

  const GLYPHS = {};
  for (const [ch, rows] of Object.entries(RAW)) GLYPHS[ch] = rows.split('|');
  for (const [lat, cyr] of Object.entries(SAME)) GLYPHS[lat] = GLYPHS[cyr];

  // Символы без начертания (эмодзи, иероглифы) пропускаем.
  function glyph(ch) {
    return GLYPHS[ch.toUpperCase()] || null;
  }

  /** Текст → массив столбцов (каждый — 7 бит), между буквами пустой столбец. */
  function columns(text) {
    const cols = [];
    for (const ch of String(text)) {
      const rows = glyph(ch);
      if (!rows) continue;
      for (let x = 0; x < 5; x += 1) {
        let col = 0;
        for (let y = 0; y < 7; y += 1) if (rows[y][x] === '#') col |= 1 << y;
        cols.push(col);
      }
      cols.push(0);
    }
    return cols;
  }

  // items — функция, возвращающая список { text, hold } или { text, scroll }; text может быть функцией.
  function createBoard({ x, y, cols, pitch = 3, dot = 2, items: getItems = null }) {
    const cfg = D.config;
    let startedAt = null; // время сцены в мс, ставится при первом кадре
    const totalMs = (cfg.countdownMinutes || 0) * 60000;
    let index = 0;
    let phaseStart = 0;
    let current = null;

    function timerText(now) {
      const left = Math.max(0, totalMs - (now - startedAt));
      const s = Math.ceil(left / 1000);
      return `${String(Math.floor(s / 60)).padStart(2, '0')}:${String(s % 60).padStart(2, '0')}`;
    }
    const timerDone = (now) => !totalMs || now - startedAt >= totalMs;

    function nextItem(now) {
      const source = getItems ? getItems() : cfg.board;
      const items = source.filter((item) => !item.onlyWithTimer || !timerDone(now))
        .map((item) => ({ ...item, text: typeof item.text === 'function' ? item.text() : item.text }))
        .filter((item) => item.text);
      if (totalMs && timerDone(now) && cfg.boardAfterTimer) items.unshift({ text: cfg.boardAfterTimer, hold: 6 });
      if (!items.length) items.push({ text: ' ', hold: 2 });
      const item = items[index % items.length];
      index += 1;
      return item;
    }

    function frameColumns(now) {
      if (!current) { current = nextItem(now); phaseStart = now; }
      const text = current.text.replace('{timer}', timerText(now));
      const data = columns(text);
      const elapsed = (now - phaseStart) / 1000;

      // длинный текст не влезает — прокручиваем
      if (current.scroll || data.length > cols) {
        const speed = current.speed || 22; // столбцов в секунду
        const offset = Math.floor(elapsed * speed) - cols;
        if (offset > data.length) { current = null; return frameColumns(now); }
        return (col) => data[col + offset] || 0;
      }
      if (elapsed > current.hold) { current = null; return frameColumns(now); }
      const pad = Math.floor((cols - data.length) / 2);
      // Появление «шторкой» сверху вниз — как у настоящих табло.
      const rowsShown = Math.min(7, Math.floor(elapsed * 30));
      const mask = (1 << rowsShown) - 1;
      return (col) => (data[col - pad] || 0) & mask;
    }

    function draw(ctx, now) {
      if (startedAt == null) startedAt = now;
      const getCol = frameColumns(now);
      // корпус
      ctx.fillStyle = '#16141b';
      ctx.fillRect(x - 5, y - 5, cols * pitch + 9, 7 * pitch + 9);
      ctx.fillStyle = '#2a2731';
      ctx.fillRect(x - 5, y - 5, cols * pitch + 9, 1);
      ctx.fillStyle = '#0b0a0e';
      ctx.fillRect(x - 3, y - 3, cols * pitch + 5, 7 * pitch + 5);
      // ножки
      ctx.fillStyle = '#1d1b22';
      for (const lx of [x + 20, x + cols * pitch - 24]) ctx.fillRect(lx, y + 7 * pitch + 4, 2, 5);

      const flicker = Math.random() < 0.004 ? 0.55 : 1;
      for (let c = 0; c < cols; c += 1) {
        const bits = getCol(c);
        for (let r = 0; r < 7; r += 1) {
          const on = bits & (1 << r);
          ctx.fillStyle = on ? (flicker < 1 ? '#c86f1f' : '#ffa53a') : '#2b1a12';
          ctx.fillRect(x + c * pitch, y + r * pitch, dot, dot);
        }
      }
      // ореол от горящих точек — без размытия, полупрозрачным слоем
      ctx.globalAlpha = 0.07 * flicker;
      ctx.fillStyle = '#ff9a2e';
      ctx.fillRect(x - 8, y - 8, cols * pitch + 15, 7 * pitch + 15);
      ctx.globalAlpha = 1;
    }

    // Сцена в OBS живёт постоянно; отсчёт начинаем заново, когда её показывают.
    function reset() { startedAt = null; current = null; index = 0; }

    return { draw, reset };
  }

  D.led = { createBoard, columns };
